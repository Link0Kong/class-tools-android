    /** 加分表：`[超出量, 加分]`（引体/仰卧高优，长跑低优）。 */
    data class FitPlusTable(val rows: List<Pair<Double, Int>>) {
        fun plusFor(gap: Double): Int {
            if (gap <= 0) return 0
            rows.forEach { (threshold, plus) -> if (gap >= threshold) return plus }
            return 0
        }
    }

